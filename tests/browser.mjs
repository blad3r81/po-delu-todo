import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless:true, ...(process.env.BROWSER_PATH ? {executablePath:process.env.BROWSER_PATH} : {})});
const context = await browser.newContext({viewport:{width:1440,height:1000}});
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await mkdir('test-results', {recursive:true});
try {
  await page.goto('http://localhost:4174/');
  assert.equal(await page.locator('.media-note,.scroll-note').count(),0);
  assert.equal(await page.locator('.header').evaluate(e => getComputedStyle(e).backgroundColor),'rgba(0, 0, 0, 0)');
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({path:'test-results/desktop-hero.png'});
  await page.getByRole('link',{name:'Открыть список'}).click();
  const input = page.getByRole('textbox',{name:'Новая задача'});
  await input.fill('   ');
  await page.getByRole('button',{name:'Добавить',exact:true}).click();
  assert.equal(await page.locator('.task-row').count(),0);
  assert.equal(await input.getAttribute('aria-invalid'),'true');
  await input.fill('Подготовить проект');
  await input.press('Enter');
  await input.fill('<img src=x onerror=alert(1)>');
  await input.press('Enter');
  assert.equal(await page.locator('.task-row').count(),2);
  assert.equal(await page.locator('.task-row img').count(),0);
  await page.getByRole('checkbox',{name:'Выполнено: Подготовить проект',exact:true}).check();
  await page.reload();
  assert.equal(await page.getByRole('checkbox',{name:'Выполнено: Подготовить проект',exact:true}).isChecked(),true);
  assert.equal(await page.locator('.task-row').count(),2);
  await page.getByRole('button',{name:/^Готово/}).click();
  assert.equal(await page.locator('.task-row').count(),1);
  await page.getByRole('button',{name:/^Активные/}).click();
  assert.equal(await page.locator('.task-row').count(),1);
  await page.getByRole('button',{name:/^Все /}).click();
  await page.getByRole('button',{name:'Удалить: Подготовить проект',exact:true}).click();
  assert.equal(await page.locator('.task-row').count(),1);
  await page.getByRole('button',{name:'Вернуть',exact:true}).click();
  assert.equal(await page.locator('.task-row').count(),2);
  await page.getByRole('button',{name:'Убрать готовые',exact:true}).click();
  await page.reload();
  assert.equal(await page.locator('.task-row').count(),1);
  const second = await context.newPage();
  await second.goto('http://localhost:4174/');
  await input.fill('Сверить мобильную версию');
  await input.press('Enter');
  await second.waitForFunction(() => document.querySelectorAll('.task-row').length === 2);
  await second.close();
  await input.fill('Очень длинная задача '.repeat(8));
  await input.press('Enter');
  for (const width of [320,390,768,1440]) {
    await page.setViewportSize({width,height:900});
    await page.locator('#tasks').scrollIntoViewIfNeeded();
    await page.waitForTimeout(250);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),`overflow at ${width}`);
    await page.screenshot({path:`test-results/tasks-${width}.png`});
  }
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(() => scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:'test-results/mobile-hero.png'});
  await page.waitForFunction(() => document.querySelector('video').readyState >= 2);
  assert.ok(await page.locator('video').evaluate(v => v.duration > 18),'the new clip should last about 20 seconds');
  await page.evaluate(() => scrollTo({top:200,behavior:'instant'}));
  await page.waitForTimeout(200);
  const first = await page.locator('video').evaluate(v => v.currentTime);
  await page.evaluate(() => scrollTo({top:400,behavior:'instant'}));
  await page.waitForTimeout(200);
  const next = await page.locator('video').evaluate(v => v.currentTime);
  assert.ok(next > first + .5,'video time should track scroll');
  assert.ok(next - first < 3,'200px of scroll should advance the video gradually');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.reload();
  assert.equal(await page.locator('video').getAttribute('src'),null);
  assert.deepEqual(errors,[]);
  console.log('PASS: add, blank input, safe text, completion, delete, undo, reload persistence, filters, tab sync, 4 viewports, video seek, reduced motion.');
} finally { await browser.close(); }
