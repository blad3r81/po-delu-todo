import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const baseUrl = process.env.BASE_URL || 'https://po-delu-todo.vercel.app/';
const browser = await chromium.launch({headless:true, ...(process.env.BROWSER_PATH ? {executablePath:process.env.BROWSER_PATH} : {})});
const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await mkdir('docs/screenshots',{recursive:true});
try {
  const response = await page.goto(baseUrl);
  assert.equal(response.status(),200);
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({path:'docs/screenshots/hero.png'});
  await page.getByRole('link',{name:'Мои задачи',exact:true}).click();
  const input = page.getByRole('textbox',{name:'Новая задача'});
  await input.fill('Подготовить тестовое задание');
  await input.press('Enter');
  await page.getByRole('heading',{name:'Мои задачи',exact:true}).click();
  assert.equal(await page.locator('.task-row').count(),1);
  await page.screenshot({path:'docs/screenshots/task-added.png'});
  await page.reload();
  assert.equal(await page.locator('.task-row').count(),1);
  const checkbox = page.getByRole('checkbox',{name:'Выполнено: Подготовить тестовое задание',exact:true});
  assert.equal(await checkbox.isChecked(),false);
  await checkbox.check();
  await page.reload();
  assert.equal(await checkbox.isChecked(),true);
  await page.getByRole('heading',{name:'Мои задачи',exact:true}).click();
  await page.screenshot({path:'docs/screenshots/task-completed.png'});
  await page.setViewportSize({width:390,height:844});
  await page.locator('#tasks').scrollIntoViewIfNeeded();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({path:'docs/screenshots/mobile.png'});
  await page.getByRole('button',{name:'Удалить: Подготовить тестовое задание',exact:true}).click();
  await page.reload();
  assert.equal(await page.locator('.task-row').count(),0);
  assert.deepEqual(errors,[]);
  const media = await context.request.get(new URL('assets/planning-long.mp4',baseUrl).href);
  assert.equal(media.status(),200);
  assert.ok(media.headers()['content-type'].includes('video/mp4'));
  console.log(JSON.stringify({site:baseUrl,passed:['public HTTP 200','add task','reload persists active task','complete task','reload persists completed task','mobile fits','delete survives reload','no page errors','video loads'],screenshots:4}));
} finally { await browser.close(); }
